import json
import time
from typing import List, Optional, Dict, Any
from mobitrade.llm.base import LocalLLMProvider

class MockLLMProvider(LocalLLMProvider):
    """
    Deterministic mock provider for unit testing and offline verification.
    Enforces that only one model is loaded at a time.
    """
    def __init__(
        self,
        available_models: Optional[List[str]] = None,
        default_response_type: str = "BUY"
    ):
        super().__init__(provider_name="MOCK_LLM", provider_version="1.0.0")
        self.available_models = available_models or [
            "nemotron-3-nano:latest",
            "qwen2.5-coder:1.5b",
            "gemma3:1b",
            "llama3.2:1b",
            "granite4:1b-h",
            "phi4-mini:latest",
            "smollm2:1.7b",
            "falcon3:1b-instruct-q4_K_M"
        ]
        self.default_response_type = default_response_type
        self.custom_responses: Dict[str, str] = {}
        self.load_history: List[str] = []
        self.unload_history: List[str] = []
        self.simulated_latency_ms: float = 15.0
        self.timeout_models: set = set()

    def set_custom_response(self, model_tag: str, response_json_str: str) -> None:
        self.custom_responses[model_tag] = response_json_str

    def set_model_timeout(self, model_tag: str) -> None:
        self.timeout_models.add(model_tag)

    def list_models(self) -> List[str]:
        return list(self.available_models)

    def load_model(self, model_tag: str) -> float:
        if self.currently_loaded_model and self.currently_loaded_model != model_tag:
            raise RuntimeError(
                f"Resource Violation: Cannot load '{model_tag}' while '{self.currently_loaded_model}' is already loaded in VRAM!"
            )
        self.currently_loaded_model = model_tag
        self.load_history.append(model_tag)
        return 10.0 # 10 ms simulated load

    def unload_model(self, model_tag: str) -> float:
        if self.currently_loaded_model == model_tag:
            self.currently_loaded_model = None
            self.unload_history.append(model_tag)
        return 5.0 # 5 ms simulated unload

    def generate(
        self,
        model_tag: str,
        prompt: str,
        system_prompt: Optional[str] = None,
        schema: Optional[Dict[str, Any]] = None,
        timeout_seconds: float = 30.0
    ) -> Dict[str, Any]:
        if model_tag not in self.available_models:
            raise ValueError(f"Unknown model tag: {model_tag}")

        if model_tag in self.timeout_models:
            raise TimeoutError(f"Simulated timeout exceeded for model {model_tag}")

        # Check for custom configured mock response
        if model_tag in self.custom_responses:
            raw = self.custom_responses[model_tag]
        else:
            # Default structured response
            action = self.default_response_type
            raw = json.dumps({
                "action": action,
                "confidence": 0.85,
                "entry_rationale": "Strong momentum and volume breakout above 20-period SMA.",
                "proposed_stop_loss": 98.5,
                "proposed_target": 105.0,
                "holding_intent": "INTRADAY",
                "reasoning_summary": f"Deterministic signal generated by {model_tag}."
            })

        return {
            "raw_text": raw,
            "latency_ms": self.simulated_latency_ms,
            "tokens_prompt": 120,
            "tokens_generated": 65,
            "metadata": {"mock": True, "model": model_tag}
        }

    def health_check(self) -> bool:
        return True
