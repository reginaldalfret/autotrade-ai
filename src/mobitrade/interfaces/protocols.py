from typing import Protocol, List, Optional
from datetime import datetime
from mobitrade.domain.models import MarketTick, OHLCVCandle, MarketSnapshot, TechnicalFeatures, Position, PortfolioSnapshot
from mobitrade.domain.trading import TradingSignal, TradeDecision, OrderRequest, Order, Execution, Trade
from mobitrade.domain.risk import RiskCheckResult
from mobitrade.domain.sources import ExternalSource
from mobitrade.domain.reporting import PerformanceMetrics

class MarketDataProvider(Protocol):
    def get_latest_tick(self, symbol: str) -> MarketTick: ...
    def get_historical_candles(self, symbol: str, start: datetime, end: datetime) -> List[OHLCVCandle]: ...

class MarketAdapter(Protocol):
    def get_market_type(self) -> str: ...
    def is_market_open(self, timestamp: datetime) -> bool: ...

class FeatureCalculator(Protocol):
    def calculate(self, candles: List[OHLCVCandle]) -> TechnicalFeatures: ...

class OpportunityScanner(Protocol):
    def scan_opportunities(self, timestamp: datetime, candidates: List[str]) -> List[str]: ...

class SourceProvider(Protocol):
    def fetch_sources(self, since: datetime, until: datetime) -> List[ExternalSource]: ...

class SourceManager(Protocol):
    def get_eligible_sources(self, timestamp: datetime, symbol: Optional[str] = None) -> List[ExternalSource]: ...

class LLMProvider(Protocol):
    def propose_decision(self, snapshot: MarketSnapshot, prompt_template: str) -> TradeDecision: ...

class Strategy(Protocol):
    def generate_signal(self, snapshot: MarketSnapshot) -> Optional[TradingSignal]: ...

class RiskManager(Protocol):
    def validate_proposal(self, decision: TradeDecision, portfolio: PortfolioSnapshot, current_trades_count: int) -> RiskCheckResult: ...

class Broker(Protocol):
    def submit_order(self, request: OrderRequest) -> Order: ...
    def cancel_order(self, order_id: str) -> bool: ...
    def get_open_positions(self, model_id: str) -> List[Position]: ...

class PortfolioManager(Protocol):
    def get_snapshot(self, model_id: str) -> PortfolioSnapshot: ...
    def update_with_execution(self, execution: Execution): ...
    def compound_daily_balance(self, model_id: str) -> float: ...

class BacktestEngine(Protocol):
    def run(self, start_date: datetime, end_date: datetime): ...

class BenchmarkEvaluator(Protocol):
    def evaluate(self, experiment_id: str) -> List[PerformanceMetrics]: ...

class ReportGenerator(Protocol):
    def generate_daily_report(self, date: str, output_path: str) -> str: ...

class TaxCalculator(Protocol):
    def calculate_tax(self, trades: List[Trade], asset_type: str) -> float: ...
